const groupNames = {
  Work:'Daily warehouse work', Review:'Review unfinished work',
  Stocktaking:'Count and correct stock', Products:'Manage products',
  Locations:'Manage locations and lights', Reports:'Use warehouse reports',
  Hardware:'Set up hardware', Administration:'Manage people and settings',
  Backups:'Keep and restore backups',
};
export function permissionPresentation(capability) {
  const [label, description = ''] = labels[capability.id] || [capability.label];
  return {...capability, label, description, primary:main.has(capability.id)};
}
export function permissionGroups(catalog) {
  return [...new Set(catalog.map(capability=>capability.group))].map(group=>({
    id:group, label:groupNames[group]||group,
    permissions:catalog.filter(capability=>capability.group===group).map(permissionPresentation),
  }));
}
